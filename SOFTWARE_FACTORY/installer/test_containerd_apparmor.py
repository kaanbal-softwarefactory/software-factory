"""Tests de la plantilla de containerd que desactiva su perfil AppArmor.

Un error aquí deja la plantilla mal formada y k3s no arranca, o la escribe en
un nodo donde alguien ya tenía la suya. Por eso se prueba la forma exacta del
TOML y que nunca se pise una plantilla ajena.
"""

import os
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import containerd_apparmor as ca  # noqa: E402

V3 = """# File generated by k3s. DO NOT EDIT. Use config-v3.toml.tmpl instead.
version = 3
root = "/var/lib/rancher/k3s/agent/containerd"

[plugins.'io.containerd.grpc.v1.cri']
  stream_server_address = "127.0.0.1"

[plugins.'io.containerd.cri.v1.runtime']
  enable_selinux = false
  enable_unprivileged_ports = true

[plugins.'io.containerd.cri.v1.runtime'.cni]
  bin_dirs = ["/var/lib/rancher/k3s/data/cni"]
"""

V2 = """# File generated by k3s. DO NOT EDIT. Use config.toml.tmpl instead.
version = 2

[plugins."io.containerd.grpc.v1.cri"]
  stream_server_address = "127.0.0.1"
  enable_selinux = false

[plugins."io.containerd.grpc.v1.cri".containerd]
  snapshotter = "overlayfs"
"""


def settings(text):
    """Líneas de configuración disable_apparmor (sin contar comentarios)."""
    return sum(1 for ln in text.splitlines() if ln.strip().startswith("disable_apparmor"))


def section_body(text, header):
    lines = text.splitlines()
    i = lines.index(header)
    body = []
    for ln in lines[i + 1:]:
        if ln.startswith("["):
            break
        body.append(ln.strip())
    return body


class RenderTest(unittest.TestCase):
    def test_v3_adds_key_only_in_runtime_section(self):
        out = ca.render_template(V3)
        body = section_body(out, "[plugins.'io.containerd.cri.v1.runtime']")
        self.assertIn("disable_apparmor = true", body)
        self.assertEqual(settings(out), 1)
        self.assertIn("enable_selinux = false", body)
        self.assertNotIn("DO NOT EDIT", out)
        self.assertTrue(out.startswith(ca.MARKER))
        # El resto del config queda igual.
        self.assertIn('bin_dirs = ["/var/lib/rancher/k3s/data/cni"]', out)
        self.assertIn('version = 3', out)

    def test_v2_uses_grpc_cri_section(self):
        out = ca.render_template(V2)
        body = section_body(out, '[plugins."io.containerd.grpc.v1.cri"]')
        self.assertIn("disable_apparmor = true", body)
        self.assertEqual(settings(out), 1)

    def test_idempotent_and_overrides_false(self):
        once = ca.render_template(V3)
        self.assertEqual(settings(ca.render_template(once)), 1)
        forced = V3.replace("  enable_selinux = false", "  enable_selinux = false\n  disable_apparmor = false")
        out = ca.render_template(forced)
        self.assertIn("disable_apparmor = true", out)
        self.assertNotIn("disable_apparmor = false", out)

    def test_missing_section_raises(self):
        with self.assertRaises(ca.TemplateError):
            ca.render_template("version = 3\n[grpc]\n  address = \"x\"\n")

    def test_template_name_by_version(self):
        self.assertEqual(ca.template_name(V3), "config-v3.toml.tmpl")
        self.assertEqual(ca.template_name(V2), "config.toml.tmpl")


class ApplyTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.dir = self.tmp.name
        with open(os.path.join(self.dir, "config.toml"), "w", encoding="utf-8") as fh:
            fh.write(V3)
        self.aa = os.path.join(self.dir, "aa-enabled")
        with open(self.aa, "w", encoding="utf-8") as fh:
            fh.write("Y\n")
        self.tmpl = os.path.join(self.dir, "config-v3.toml.tmpl")

    def tearDown(self):
        self.tmp.cleanup()

    def test_writes_template_then_skips(self):
        action, path = ca.apply(self.dir, self.aa, environ={})
        self.assertEqual((action, path), ("write", self.tmpl))
        with open(self.tmpl, encoding="utf-8") as fh:
            self.assertIn("disable_apparmor = true", fh.read())
        action, _ = ca.apply(self.dir, self.aa, environ={})
        self.assertEqual(action, "skip")

    def test_never_touches_foreign_template(self):
        with open(self.tmpl, "w", encoding="utf-8") as fh:
            fh.write("{{ template \"base\" . }}\n")
        action, _ = ca.apply(self.dir, self.aa, environ={})
        self.assertEqual(action, "foreign")
        with open(self.tmpl, encoding="utf-8") as fh:
            self.assertEqual(fh.read(), "{{ template \"base\" . }}\n")

    def test_skips_without_apparmor(self):
        with open(self.aa, "w", encoding="utf-8") as fh:
            fh.write("N\n")
        self.assertEqual(ca.apply(self.dir, self.aa, environ={})[0], "skip")
        self.assertEqual(ca.apply(self.dir, os.path.join(self.dir, "nope"), environ={})[0], "skip")
        self.assertFalse(os.path.exists(self.tmpl))

    def test_keep_policy_opts_out(self):
        action, detail = ca.apply(self.dir, self.aa, environ={ca.POLICY_ENV: "keep"})
        self.assertEqual(action, "skip")
        self.assertIn("keep", detail)
        self.assertFalse(os.path.exists(self.tmpl))

    def test_unknown_policy_falls_back_to_disable(self):
        self.assertEqual(ca.policy({ca.POLICY_ENV: "loquesea"}), "disable")
        self.assertEqual(ca.policy({}), "disable")

    def test_cli_check_does_not_write(self):
        # --check usa la ruta real de AppArmor del host; solo comprobamos que no escribe.
        rc = ca.main(["--check", "--containerd-dir", self.dir])
        self.assertEqual(rc, 0)
        self.assertFalse(os.path.exists(self.tmpl))


if __name__ == "__main__":
    unittest.main()
